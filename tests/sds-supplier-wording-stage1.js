'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {extract}=require('../sds-supplier-wording.js');
const source='2.2 Label elements\nP333+P313 If skin irritation or rash occurs: Get medical advice/attention.\nP103 Read carefully and follow all instructions.\nP280 Wear protective gloves.';
const got=extract(source);
assert.equal(got['P333+P313'],'If skin irritation or rash occurs: Get medical advice/attention.');
assert.equal(got.P103,'Read carefully and follow all instructions.');
assert.equal(got.P280,'Wear protective gloves.');
assert.equal(extract('H317 May cause an allergic skin reaction.').H317,'May cause an allergic skin reaction.');
assert.equal(extract('EUH208 Contains Limonene. May produce an allergic reaction.').EUH208,'Contains Limonene. May produce an allergic reaction.');
assert.equal(extract('P305 + P351 + P338 IF IN EYES: Rinse cautiously with water for several minutes. Remove contact lenses, if present and easy to do. Continue rinsing.')['P305+P351+P338'], 'IF IN EYES: Rinse cautiously with water for several minutes. Remove contact lenses, if present and easy to do. Continue rinsing.');

const wrapped=extract('P305+P351+P338 IF IN EYES: Rinse cautiously with water for several minutes.\nRemove contact lenses, if present and easy to do.\nContinue rinsing.\nP313 Get medical advice/attention.');
assert.equal(wrapped['P305+P351+P338'],'IF IN EYES: Rinse cautiously with water for several minutes. Remove contact lenses, if present and easy to do. Continue rinsing.');
assert.equal(wrapped.P313,'Get medical advice/attention.');
const headings=extract('P101 If medical advice is needed, have product container or label at hand.\nPrecautionary statements:\nP102 Keep out of reach of children.');
assert.equal(headings.P101,'If medical advice is needed, have product container or label at hand.');
assert.equal(Object.keys(extract('')).length,0);
assert.equal(extract('H350i May cause cancer by inhalation.').H350i,'May cause cancer by inhalation.');
const repeated=extract('P313 First text.\nP313 Different text.\nP313 Third text.');
assert.equal(repeated.P313,undefined,'ambiguous repeated codes must never silently select a wording');
console.log('Supplier wording parser checks PASS');
